import dayjs from 'dayjs';
import * as XLSX from 'xlsx';

import type { TemplateFile, TemplateFormat } from '@/types';

/**
 * 模板文件工具：格式元数据、体积格式化、各格式示例内容生成与浏览器端下载。
 *
 * 内置种子模板并无真实文件，下载时按格式生成演示内容（xlsx 为真实工作簿、
 * doc/docx 为 Word 兼容 HTML、pdf 为最小 PDF 文档）；用户上传的模板则回放原始字节。
 */

export const FORMAT_META: Record<TemplateFormat, { label: string; color: string }> = {
  doc: { label: 'DOC', color: '#4a6fe3' },
  docx: { label: 'DOCX', color: '#5f86ff' },
  xls: { label: 'XLS', color: '#55906c' },
  xlsx: { label: 'XLSX', color: '#6fae85' },
  pdf: { label: 'PDF', color: '#d9645c' },
};

export const TEMPLATE_ACCEPT = '.doc,.docx,.xls,.xlsx,.pdf';
export const TEMPLATE_MAX_SIZE = 10 * 1024 * 1024;

/** 从文件名解析受支持的格式，不支持时返回 null */
export function extFormat(filename: string): TemplateFormat | null {
  const ext = filename.toLowerCase().match(/\.([a-z0-9]+)$/)?.[1] ?? '';
  return (Object.keys(FORMAT_META) as string[]).includes(ext) ? (ext as TemplateFormat) : null;
}

export function formatSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(0)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}

const escapeHtml = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** 生成 doc / docx 的 Word 兼容 HTML 文档 */
function wordBlob(t: TemplateFile): Blob {
  const name = escapeHtml(t.name);
  const desc = escapeHtml(t.description ?? '—');
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${name}</title></head>
<body style="font-family:'SimSun','Songti SC',serif;">
<h2 style="text-align:center;">${name}</h2>
<p style="text-align:center;color:#666;">申请表模板汇总库 · 示例文档</p>
<p><b>模板说明：</b>${desc}</p>
<p><b>使用说明：</b>下载后按实际业务填写并打印签字；本示例文档由模板汇总库生成，接入真实后端后可下载原始文件。</p>
<p><b>更新时间：</b>${t.updatedAt}　　<b>上传者：</b>${escapeHtml(t.uploader)}</p>
<br/>
<table border="1" cellspacing="0" cellpadding="8" style="border-collapse:collapse;width:100%;">
<tr><td style="width:25%;">姓名</td><td style="width:25%;"></td><td style="width:25%;">学号</td><td style="width:25%;"></td></tr>
<tr><td>班级</td><td></td><td>联系电话</td><td></td></tr>
<tr><td>申请事项</td><td colspan="3" style="height:90px;"></td></tr>
<tr><td>学生签名</td><td></td><td>日期</td><td></td></tr>
<tr><td>辅导员意见</td><td colspan="3" style="height:70px;"></td></tr>
<tr><td>学院意见</td><td colspan="3" style="height:70px;"></td></tr>
</table>
</body></html>`;
  return new Blob(['\ufeff', html], { type: 'application/msword' });
}

/** 生成 xls / xlsx 真实工作簿 */
function sheetBlob(t: TemplateFile): Blob {
  const wb = XLSX.utils.book_new();
  const ws = XLSX.utils.aoa_to_sheet([
    [t.name],
    [],
    ['模板说明', t.description ?? '—'],
    ['上传者', t.uploader],
    ['更新时间', t.updatedAt],
    [],
    ['使用说明', '本文件由模板汇总库生成的示例内容；接入真实后端后可下载原始文件。'],
    [],
    ['姓名', '学号', '班级', '申请事项', '日期'],
    ['', '', '', '', ''],
    ['', '', '', '', ''],
  ]);
  ws['!cols'] = [{ wch: 18 }, { wch: 16 }, { wch: 14 }, { wch: 30 }, { wch: 14 }];
  XLSX.utils.book_append_sheet(wb, ws, '模板信息');
  const out = XLSX.write(wb, {
    bookType: t.format === 'xls' ? 'xls' : 'xlsx',
    type: 'array',
  }) as ArrayBuffer;
  return new Blob([out], {
    type:
      t.format === 'xls'
        ? 'application/vnd.ms-excel'
        : 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });
}

/** 生成最小可用的 PDF（内容为 ASCII，中文以连字符占位） */
function pdfBlob(t: TemplateFile): Blob {
  const ascii = (s: string) => s.replace(/[^\x20-\x7e]/g, '-').replace(/([()\\])/g, '\\$1');
  const meta = [
    'Category / Apply Template Library',
    `Description: ${(t.description ?? '-').replace(/[^\x20-\x7e]/g, '-')}`.slice(0, 90),
    `Updated: ${t.updatedAt}    By: ${ascii(t.uploader)}`,
    'Note: demo content generated by the template library.',
  ];
  const parts = [
    'BT', '/F1 18 Tf', '56 780 Td', `(${ascii(t.name)}) Tj`, 'ET',
    ...meta.flatMap((line, i) => ['BT', '/F1 10 Tf', `56 ${746 - i * 18} Td`, `(${ascii(line)}) Tj`, 'ET']),
  ];
  const stream = parts.join('\n');
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];
  objs.forEach((body, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefPos = pdf.length;
  pdf += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('');
  pdf += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF`;
  return new Blob([pdf], { type: 'application/pdf' });
}

/** 构建模板下载内容：有上传字节时回放原文件，否则按格式生成示例内容 */
export function buildTemplateBlob(t: TemplateFile, bytes?: Uint8Array): Blob {
  if (bytes && bytes.length > 0) return new Blob([bytes.buffer as ArrayBuffer]);
  switch (t.format) {
    case 'xls':
    case 'xlsx':
      return sheetBlob(t);
    case 'pdf':
      return pdfBlob(t);
    default:
      return wordBlob(t);
  }
}

/** 触发浏览器保存文件 */
export function saveBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

/** 当前日期串（用于导出命名等） */
export function todayTag(): string {
  return dayjs().format('YYYYMMDD-HHmm');
}
